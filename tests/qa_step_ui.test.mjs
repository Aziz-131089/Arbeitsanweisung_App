import assert from 'node:assert/strict';
import vm from 'node:vm';
import { applicationSource } from './helpers.mjs';
const src=await applicationSource();
const ctx=vm.createContext({console,setTimeout,clearTimeout,atob});
vm.runInContext(src,ctx);
const run=expr=>vm.runInContext(expr,ctx), plain=v=>JSON.parse(JSON.stringify(v));
assert.equal(run('nextMarkerNumber([])'),1);
assert.equal(run("nextMarkerNumber([{typ:'nummer',nummer:1},{typ:'kreis'},{typ:'nummer',nummer:4}])"),5);
assert.equal(run("nextMarkerNumber([{typ:'nummer',nummer:999}])"),1);
ctx.form=[{typ:'nummer',cx:100,cy:120,r:16,nummer:3},{typ:'nummer',cx:0,cy:0,r:10,nummer:0}];
assert.deepEqual(plain(run('sanitizeForms(form)')),[{typ:'nummer',cx:100,cy:120,r:16,nummer:3}]);
ctx.state={formen:plain(run('sanitizeForms(form)'))};run('transformForms(state,{x:0,y:0,w:200,h:200},{x:10,y:20,w:400,h:400})');
assert.deepEqual(ctx.state.formen,[{typ:'nummer',cx:210,cy:260,r:32,nummer:3}]);
ctx.draft={version:3,logoDataUrl:'',docBildgroesse:'kompakt',schritte:[{kurztitel:'Prüfen',taetigkeit:'1 – Merkmal prüfen',formen:ctx.state.formen,werkzeug:'nummer'}]};
const normalized=run('normalizeStand(draft)');
assert.equal(normalized.docBildgroesse,'kompakt');assert.equal(normalized.schritte[0].kurztitel,'Prüfen');assert.equal(normalized.schritte[0].formen[0].nummer,3);assert.equal(normalized.schritte[0].werkzeug,'nummer');
assert.deepEqual(plain(run("documentStepColumns([{image:{width:750,height:1000}}],'kompakt')")),[7,34,59]);
assert.deepEqual(plain(run("photoPrintDimensions({width:750,height:1000},LAYOUT.compactPortraitCols,'kompakt')")),{width:48.75,height:65});
console.log('PASS: numbered markers, transform and persistence, optional title and compact image sizing.');
